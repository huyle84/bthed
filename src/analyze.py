#!/usr/bin/env python3
"""Analyse Stage-1 results (../results/*.csv) and write ../results/RESULTS.md."""
import csv, glob, math, os, re, sys

R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'results')
PS = {'mldsa44': dict(k=4, l=4, beta=78, g1=2**17, g2=(8380417 - 1) // 88, name='ML-DSA-44'),
      'mldsa65': dict(k=6, l=5, beta=196, g1=2**19, g2=(8380417 - 1) // 32, name='ML-DSA-65'),
      'mldsa87': dict(k=8, l=7, beta=120, g1=2**19, g2=(8380417 - 1) // 32, name='ML-DSA-87')}


def read(path):
    hdr, rows = [], []
    with open(path) as f:
        lines = [x for x in f if x.strip()]
    for x in lines:
        if x.startswith('#'):
            hdr.append(x.strip('# \n'))
    data = [x for x in lines if not x.startswith('#')]
    blocks, cur = [], []
    for x in data:
        if x.split(',')[0] in ('mode', 'timing_us', 'operation', 'n') and cur:
            blocks.append(cur); cur = []
        cur.append(x)
    if cur: blocks.append(cur)
    return hdr, [list(csv.DictReader(b)) for b in blocks]


def se(p, n):
    return math.sqrt(max(p * (1 - p), 1e-300) / n)


def heur(ps, mode):
    pz = ((2 * ps['g1'] - 2 * ps['beta'] - 1) / (2 * ps['g1'])) ** (256 * ps['l'])
    m = 2 * ps['beta'] if mode == 'DOUBLE' else ps['beta']
    pr = ((2 * ps['g2'] - 2 * m - 1) / (2 * ps['g2'])) ** (256 * ps['k'])
    return pz, pr


def pL(pa, pf, L):
    return (1 - (1 - pa) ** L) * pf


out = ['# BTHED Stage-1 (cleartext) results', '',
       'Generated by `analyze.py` from the CSV files in this folder. All runs use the pq-crystals ML-DSA reference '
       'code (FIPS 204); every produced signature is checked with the **unmodified** reference verifier.', '']
envf = os.path.join(R, 'environment.txt')
if os.path.exists(envf):
    out += ['**Environment.** ' + '; '.join(x.strip() for x in open(envf) if x.strip()), '']

# ---------------------------------------------------------------- stats
out += ['## 1. Per-attempt statistics (b_e = 3, i.e. B_e = 4)', '',
        '| Param | Mode | attempts | p_z (theory) | p_r (theory) | p_accept ± 2σ | P[Fin ok \\| accept] | signatures | verify failures |',
        '|---|---|---|---|---|---|---|---|---|']
stats = {}
for key in PS:
    f = os.path.join(R, f'stats_{key}_be3.csv')
    if not os.path.exists(f): continue
    _, bl = read(f)
    for r in bl[0]:
        n = int(r['attempts']); pa = float(r['p_accept']); pf = float(r['p_fin_given_accept'])
        stats[(key, r['mode'])] = (pa, pf, n)
        hz, hr = heur(PS[key], r['mode'] if r['mode'] != 'STD' else 'STD')
        out.append(f"| {PS[key]['name']} | {r['mode']} | {n} | {float(r['p_z']):.4f} ({hz:.4f}) | "
                   f"{float(r['p_r']):.4f} ({hr:.4f}) | {pa:.4f} ± {2*se(pa,n):.4f} | {pf:.4f} | "
                   f"{r['signatures']} | **{r['verify_failures']}** |")
out.append('')

# ---------------------------------------------------------------- L
out += ['## 2. Number of parallel attempts L', '',
        'Since attempts are i.i.d. and Fin only depends on the first accepted attempt, '
        '`p_L = (1-(1-p_accept)^L) * P[Fin ok | accept]`. `L_eq` is the smallest L for which a mode reaches the '
        'success probability of BTHED (= the THED rule) with L = 8; `L(1e-3)`/`L(1e-6)` make the probability that '
        '*no* attempt is accepted at most 10^-3 / 10^-6.', '',
        '| Param | Mode | p_L(8) | p_L(20) | L_eq (vs BTHED, L=8) | L(1e-3) | L(1e-6) |', '|---|---|---|---|---|---|---|']
for key in PS:
    if (key, 'BTHED') not in stats: continue
    tgt = pL(*stats[(key, 'BTHED')][:2], 8)
    for md in ('STD', 'BTHED', 'DOUBLE'):
        pa, pf, _ = stats[(key, md)]
        leq = next(L for L in range(1, 500) if pL(pa, pf, L) >= tgt * (1 - 1e-12))
        l3 = math.ceil(math.log(1e-3) / math.log(1 - pa)); l6 = math.ceil(math.log(1e-6) / math.log(1 - pa))
        out.append(f"| {PS[key]['name']} | {md} | {pL(pa,pf,8):.4f} | {pL(pa,pf,20):.4f} | {leq} | {l3} | {l6} |")
out.append('')

# ---------------------------------------------------------------- sessions
out += ['## 3. Full-session simulation (Req → C1 → Chal → C2 → Fin → Verify)', '',
        '| Param | L | Mode | sessions | p_L measured | p_L predicted | no accepted attempt | Fin failure | verify failures |',
        '|---|---|---|---|---|---|---|---|---|']
timing = []
for f in sorted(glob.glob(os.path.join(R, 'session_*_L*.csv'))):
    key, L = re.search(r'session_(\w+)_L(\d+)', f).groups(); L = int(L)
    _, bl = read(f)
    for r in bl[0]:
        n = int(r['sessions']); p = float(r['p_L'])
        pr = pL(*stats[(key, r['mode'])][:2], L) if (key, r['mode']) in stats else float('nan')
        out.append(f"| {PS[key]['name']} | {L} | {r['mode']} | {n} | {p:.4f} ± {2*se(p,n):.4f} | {pr:.4f} | "
                   f"{r['no_accepted_attempt']} | {r['fin_fail']} | **{r['verify_failures']}** |")
    if len(bl) > 1:
        t = bl[1][0]; timing.append((PS[key]['name'], L, t))
out.append('')
out += ['## 4. Cleartext cost per BTHED session (mean µs, single core)', '',
        'These are the costs of the same computations *without* encryption: a lower bound, and the baseline for '
        'the FHE overhead factor of Stage 2. The user-side columns (Req without encryption, Chal, Fin) are '
        'real costs of the user in BTHED (to which encryption and the NIZK must be added).', '',
        '| Param | L | user Req | signers C1 | user Chal | signers C2 | user Fin | Verify |', '|---|---|---|---|---|---|---|---|']
for name, L, t in timing:
    out.append(f"| {name} | {L} | {t['user_req']} | {t['signer_C1']} | {t['user_chal']} | {t['signer_C2']} | {t['user_fin']} | {t['verify']} |")
out.append('')

# ---------------------------------------------------------------- bench
out += ['## 5. Micro-benchmarks (median ns)', '']
bench = {}
for key in PS:
    f = os.path.join(R, f'bench_{key}.csv')
    if os.path.exists(f):
        _, bl = read(f); bench[key] = {r['operation']: r['median_ns'] for r in bl[0]}
if bench:
    ops = list(next(iter(bench.values())).keys())
    out += ['| Operation | ' + ' | '.join(PS[k]['name'] for k in bench) + ' |', '|---|' + '---|' * len(bench)]
    for op in ops:
        out.append(f'| {op} | ' + ' | '.join(bench[k].get(op, '') for k in bench) + ' |')
out.append('')

# ---------------------------------------------------------------- noise size
out += ['## 6. Effect of the commitment-noise bound B_e on verification correctness', '',
        'BTHED uses the rule of THED (margin γ2−β), which is *exactly* '
        'correct as long as B_e ≤ β, since |w0 − c s2 − e| < (γ2−β) + B_e ≤ γ2 (Lemma 1). Large B_e probes the boundary '
        '(the doubled margin γ2−2β, mode DOUBLE, tolerates B_e ≤ 2β; it is kept for comparison only).', '',
        '| Param | b_e | B_e | β | Mode | signatures | verify failures |', '|---|---|---|---|---|---|---|']
for f in sorted(glob.glob(os.path.join(R, 'stats_*_be*.csv'))):
    key, b = re.search(r'stats_(\w+)_be(\d+)', f).groups()
    _, bl = read(f)
    for r in bl[0]:
        out.append(f"| {PS[key]['name']} | {b} | {2**(int(b)-1)} | {PS[key]['beta']} | {r['mode']} | {r['signatures']} | **{r['verify_failures']}** |")
out.append('')

# ---------------------------------------------------------------- rss
f = os.path.join(R, 'rss.csv')
if os.path.exists(f):
    out += ['## 7. Replicated secret sharing (exhaustive checks)', '',
            '| n | t | total shares | shares per party | active sets | reconstruction ok | coalitions |C|≤t−1 | privacy ok |',
            '|---|---|---|---|---|---|---|---|']
    _, bl = read(f)
    for b in bl:
        for r in b:
            out.append(f"| {r['n']} | {r['t']} | {r['total_shares']} | {r['shares_per_party']} | {r['active_sets']} | "
                       f"{r['reconstruct_ok']} | {r['coalitions_checked']} | {r['privacy_ok']} |")
    out.append('')

open(os.path.join(R, 'RESULTS.md'), 'w').write('\n'.join(out) + '\n')
print('\n'.join(out))
